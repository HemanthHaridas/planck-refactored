#!/usr/bin/env python3
"""Regenerate src/lookup/loader/signing_key.cpp from planck_signing_public.pem.

Run this after rotating the signing key (the private key is kept outside
this repository).

Usage (from repo root):
    python3 src/lookup/keys/generate_embedded_key.py
"""
import base64
import os

REPO_ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))))
PEM_PATH = os.path.join(REPO_ROOT, "src/lookup/keys/planck_signing_public.pem")
OUT_PATH = os.path.join(REPO_ROOT, "src/lookup/loader/signing_key.cpp")


def main():
    with open(PEM_PATH) as f:
        lines = [l.strip() for l in f if not l.startswith("-----")]
    der = base64.b64decode("".join(lines))
    hex_bytes = ", ".join(f"0x{b:02x}" for b in der)

    with open(OUT_PATH, "w") as f:
        f.write(
            "// Generated by src/lookup/keys/generate_embedded_key.py — do not hand-edit.\n"
            "// Regenerate if the signing key ever rotates.\n"
            '#include "lookup/loader/license.h"\n\n'
            "namespace HartreeFock::Loader\n"
            "{\n"
            f"    extern const unsigned char kPlanckSigningPublicKeyDer[{len(der)}] = {{{hex_bytes}}};\n"
            f"    extern const std::size_t kPlanckSigningPublicKeyDerLen = {len(der)};\n"
            "} // namespace HartreeFock::Loader\n"
        )
    print(f"Wrote {OUT_PATH} ({len(der)} bytes)")


if __name__ == "__main__":
    main()
