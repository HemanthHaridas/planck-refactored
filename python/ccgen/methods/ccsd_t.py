"""CCSD(T) perturbative-triples generation (docs/CCSD_T_SCOPE.md step 1).

Not a residual: (T) needs two triples-manifold projections of a bare operator
product, no BCH expansion,

    W_ijk^abc = <Phi_ijk^abc | (V_N T2)_C | 0>     connected
    V_ijk^abc = <Phi_ijk^abc | V_N T1 | 0>         disconnected only

and the scalar  E(T) = (1/36) sum (W + V) W / D_ijk^abc  in spin orbitals,
with a canonical reference (f_ov = 0) so F_N contributes only through D.
"""

from __future__ import annotations

import re

from ..algebra import multiply
from ..cluster import build_tn
from ..generate import _generate_manifold_equation
from ..hamiltonian import build_two_body_operator
from ..project import AlgebraTerm


def _project_triples(product, connected_only: bool) -> list[AlgebraTerm]:
    # ponytail: no bucket_terms_by_manifold pre-filter. Its block-connectivity
    # test assumes BCH commutator terms (connected by construction) and drops
    # the disconnected V_N T1 product outright; two bare products need no
    # pre-pruning.
    _, _, canonical = _generate_manifold_equation(
        "triples", tuple(product.terms), connected_only,
        collect_denominators=False, permutation_grouping=False,
        exploit_symmetry=False, parallel_workers=1,
    )
    return canonical


def build_ccsd_t_equations() -> dict[str, list[AlgebraTerm]]:
    """Return ``{"W": [...], "V": [...]}`` triples-manifold term lists."""
    vn = build_two_body_operator()
    w = _project_triples(multiply(vn, build_tn(2)), connected_only=True)
    # V_N T1 cannot reach triples through a connected product (it tops out at
    # doubles), so the unfiltered projection is the disconnected term alone.
    # Assert it: a connected term here would mean the projector or the
    # connectivity flag is wrong, and it would silently enter E(T).
    v_all = _project_triples(multiply(vn, build_tn(1)), connected_only=False)
    assert all(not t.connected for t in v_all), "connected term in V_N T1 triples"
    assert all({f.name for f in t.factors} == {"t1", "v"} for t in v_all)
    return {"W": w, "V": v_all}


def build_ccsd_t_restricted() -> dict[str, list[AlgebraTerm]]:
    """Closed-shell (T): W and V lowered to spatial orbitals on the aab|aab
    block (a, b, i, j alpha; c, k beta), in spatial t1, t2 (abab) and the
    non-antisymmetrized <pq|rs>.

    That one block carries the whole energy. Closed shell gives aaa = bbb and
    aab = abb, and the all-alpha block is half the full antisymmetrizer over the
    three virtuals applied to the aab block (exact, measured to 4e-14 for both
    W and V):

        X_aaa(abc, ijk) = 1/2 sum_P sign(P) X_aab(P(abc), ijk)

    so with S_blk = sum (W + V) W / D over a block,

        E(T) = (2 S_aaa + 18 S_aab) / 36 = S_aaa / 18 + S_aab / 2.
    """
    from ..spin import spin_adapt_equations

    eqs = build_ccsd_t_equations()
    for terms in eqs.values():
        # spin_adapt_equations assigns the block by slot position over these
        # names; a renamed external would silently land on another block.
        assert {i.name for i in terms[0].free_indices} == set("abcijk")
    return spin_adapt_equations(eqs)


def build_ccsd_t_unrestricted() -> dict[str, list[AlgebraTerm]]:
    """Open-shell (T): W and V on each of the four UCC triples blocks.

    Keys ``W_<tag>`` / ``V_<tag>`` for tag in aaaaaa, aabaab, abbabb, bbbbbb
    (vir a, b, c then occ i, j, k; alpha-before-beta per half). Each mixed block
    stands for 9 index arrangements and each pure block for 1, so

        E(T) = (S_aaa + S_bbb) / 36 + (S_aab + S_abb) / 4,

    with each S over its own alpha/beta denominators. There is no aaa-from-aab
    identity here: alpha and beta orbitals differ.
    """
    from ..spin import ucc_adapt_equations

    eqs = build_ccsd_t_equations()
    for terms in eqs.values():
        assert {i.name for i in terms[0].free_indices} == set("abcijk")
    return ucc_adapt_equations(eqs)


def emit_planck_ccsd_t_translation_unit() -> str:
    """The restricted (T) TU: W and V over the aab block, in two shapes.

    Full tensors (the oracle) and one-virtual-triple blocks (production),
    emitted from the same lowered terms through the same per-term product text.

    ``compute_ccsd_t_W_residual`` / ``compute_ccsd_t_V_residual`` each return a
    Tensor6D (i, j, k, a, b, c) from spatial t1/t2 (ArbitraryOrderRCCAmplitudes)
    and the physicist ERI blocks; ``src/post_hf/cc/ccsd_t.cpp`` contracts E(T).
    The emitter parses its ``method`` as a CC level, so the kernels are emitted
    under ``ccsd`` with targets ``t_W`` / ``t_V``.
    """
    from ..emit.planck_tensor_cpp import _emit_kernel

    eqs = build_ccsd_t_restricted()
    parts = [
        "// Auto-generated by ccgen (python/ccgen/methods/ccsd_t.py)",
        "// CCSD(T) W and V, restricted (aab|aab block) and unrestricted (four t3 blocks),",
        "// as full o^3 v^3 tensors (the oracle) and as o^3 blocks per virtual triple.",
        "",
        "#include <algorithm>",
        "",
        '#include "post_hf/cc/tensor_backend.h"',
        '#include "post_hf/cc/generated_arbitrary_runtime.h"',
        "",
        "namespace HartreeFock::Correlation::CC",
        "{",
        "",
    ]
    for target in ("W", "V"):
        parts.append(_emit_kernel("ccsd", f"t_{target}", eqs[target], force_arbitrary=True))
        parts.append("")
    # W for all six orderings of a triple at once (production); V per ordering.
    parts.append(_emit_triple_kernel("W", eqs["W"]))
    parts.append("")
    parts.append(_emit_block_kernel("V", eqs["V"]))
    parts.append("")
    # Unrestricted (UCCSD(T)): the same two shapes per t3 block. The types they
    # use exist in every build; only running ucc2 needs -DPLANCK_CC_UCC=ON.
    ueqs = build_ccsd_t_unrestricted()
    for key, terms in ueqs.items():
        parts.append(_emit_kernel("ccsd", f"t_{key}", terms, force_arbitrary=True, ucc=True))
        parts.append("")
        parts.append(_emit_block_kernel(key, terms, ucc=True))
        parts.append("")
    parts.append("} // namespace HartreeFock::Correlation::CC")
    return "\n".join(parts)


# The six orderings of a virtual triple (v0, v1, v2), as positions into it:
# ordering p binds (a, b, c) = (v[P[0]], v[P[1]], v[P[2]]). Must match kPerms in
# src/post_hf/cc/ccsd_t.cpp, which reads block p as that ordering.
TRIPLE_ORDERINGS = ((0, 1, 2), (1, 2, 0), (2, 0, 1), (1, 0, 2), (0, 2, 1), (2, 1, 0))

_INDEX_TOKEN = re.compile(r"\b([ijkabcdl])\b")


def _emit_triple_kernel(target: str, terms) -> str:
    """W (or V) for all six orderings of one virtual triple, into out[6 * o^3].

    Each ordering's block is the same 24 terms with (a, b, c) bound to a
    different arrangement of the triple, and each term is an o^3 elementary
    block (one contraction of two factors) up to a renaming of i, j, k. Over
    the six orderings the 144 term evaluations hit only 24 distinct elementary
    blocks, so each is computed once and every (ordering, term) adds it with
    its occupied indices transposed. Each elementary block is the same
    summation, in the same order, as the term's accumulator in the per-ordering
    kernel, and the terms are added in the same order, so the result is the
    per-ordering kernel's bitwise.
    """
    from ..emit.planck_tensor_cpp import (
        _amplitude_view_bindings, _coeff_literal, _map_factor, _orbital_count_preamble)

    keys: dict[tuple, int] = {}  # elementary block -> slot
    key_text: list[tuple] = []   # per slot: (factor texts, summed bound)
    adds: list[list[tuple]] = [[] for _ in TRIPLE_ORDERINGS]  # per ordering: (slot, coeff, occ map)
    for p, perm in enumerate(TRIPLE_ORDERINGS):
        vmap = {"a": f"v{perm[0]}", "b": f"v{perm[1]}", "c": f"v{perm[2]}"}
        for term in terms:
            assert len(term.summed_indices) == 1 and len(term.factors) == 2, term
            s = term.summed_indices[0]
            assert s.name in "dl", s
            sign, exprs = 1, []
            for f in term.factors:
                fs, e = _map_factor(f, None, True)
                sign *= fs
                exprs.append(e)
            # Occupied externals renamed u0, u1, u2 by first appearance, so terms
            # equal up to an i, j, k renaming share one block.
            occ: list[str] = []
            for e in exprs:
                occ += [x for x in _INDEX_TOKEN.findall(e) if x in "ijk" and x not in occ]
            assert sorted(occ) == ["i", "j", "k"], occ
            rename = {x: f"u{n}" for n, x in enumerate(occ)} | vmap | {s.name: s.name}
            key = tuple(_INDEX_TOKEN.sub(lambda m: rename[m.group(1)], e) for e in exprs)
            if key not in keys:
                keys[key] = len(key_text)
                key_text.append((key, s.name, "nv" if s.name == "d" else "no"))
            adds[p].append((keys[key], term.coeff * sign, occ))

    lines = [
        f"void compute_ccsd_t_{target}_triple(",
        "    int v0, int v1, int v2,",
        "    const CanonicalRHFCCReference &reference,",
        "    const TensorCCBlockCache &mo_blocks,",
        "    const ArbitraryOrderRCCAmplitudes &amplitudes,",
        "    double *out)",
        "{",
    ]
    lines += _orbital_count_preamble(False)
    lines.append("    (void)nv;")
    lines.append("    const std::size_t o3 = static_cast<std::size_t>(no) * no * no;")
    lines.append(f"    std::fill(out, out + {len(TRIPLE_ORDERINGS)} * o3, 0.0);")
    lines += _amplitude_view_bindings(terms)
    lines.append("    static thread_local std::vector<double> e;")
    lines.append(f"    if (e.size() < {len(key_text)} * o3) e.resize({len(key_text)} * o3);")
    for slot, (exprs, s, bound) in enumerate(key_text):
        lines += [
            f"    // Elementary block {slot}: {' * '.join(exprs)}",
            "    for (int u0 = 0; u0 < no; ++u0)",
            "    for (int u1 = 0; u1 < no; ++u1)",
            "    for (int u2 = 0; u2 < no; ++u2)",
            "    {",
            "        double acc = 0.0;",
            f"        for (int {s} = 0; {s} < {bound}; ++{s})",
            f"            acc += {' * '.join(exprs)};",
            f"        e[{slot} * o3 + (static_cast<std::size_t>(u0) * no + u1) * no + u2] = acc;",
            "    }",
        ]
    for p, perm in enumerate(TRIPLE_ORDERINGS):
        lines.append(f"    // Ordering {p}: (a, b, c) = (v{perm[0]}, v{perm[1]}, v{perm[2]})")
        lines += [
            "    for (int i = 0; i < no; ++i)",
            "    for (int j = 0; j < no; ++j)",
            "    for (int k = 0; k < no; ++k)",
            "    {",
            "        double &w = out[" + str(p) + " * o3 + (static_cast<std::size_t>(i) * no + j) * no + k];",
        ]
        for slot, coeff, occ in adds[p]:
            u = f"(static_cast<std::size_t>({occ[0]}) * no + {occ[1]}) * no + {occ[2]}"
            lines.append(f"        w += {_coeff_literal(coeff)}e[{slot} * o3 + {u}];")
        lines.append("    }")
    lines.append("}")
    return "\n".join(lines)


def _emit_block_kernel(target: str, terms, ucc: bool = False) -> str:
    """One (a, b, c) block of W or V: o^3 doubles over (i, j, k), row-major.

    The virtual externals are function parameters, so only the occupied
    externals and the summed index are looped. Each term's accumulation text is
    ``_term_coeff_product``, the same string the full-tensor kernel uses. With
    ``ucc`` the loop bounds, the out strides and the ERI views are per spin, and
    the symbol is ``compute_ucc_ccsd_t_<target>_block``.
    """
    from ..emit.planck_tensor_cpp import (
        _amplitude_view_bindings, _eri_view_bindings, _loop_bound,
        _orbital_count_preamble, _term_coeff_product)
    from ..spin import ucc_term_index_spins

    prefix = "ucc_" if ucc else ""
    spins = ucc_term_index_spins(terms[0]) if ucc else {}
    ni, nj, nk = (_loop_bound(next(x for x in terms[0].free_indices if x.name == n),
                              spins.get(n)) for n in "ijk")
    lines = [
        f"void compute_{prefix}ccsd_t_{target}_block(",
        "    int a, int b, int c,",
        "    const CanonicalRHFCCReference &reference,",
        "    const TensorCCBlockCache &mo_blocks,",
        "    const ArbitraryOrderRCCAmplitudes &amplitudes,",
        "    double *out)",
        "{",
    ]
    lines += _orbital_count_preamble(ucc)
    lines += [f"    (void){n};" for n in (("nva", "nvb") if ucc else ("nv",))]
    lines.append(f"    std::fill(out, out + static_cast<std::size_t>({ni}) * {nj} * {nk}, 0.0);")
    lines += _amplitude_view_bindings(terms)
    if ucc:
        lines += _eri_view_bindings(terms)
    for n, term in enumerate(terms, 1):
        occ = [i for i in term.free_indices if i.space == "occ"]
        vir = [i for i in term.free_indices if i.space == "vir"]
        # The parameters bind a, b, c and out is laid out over i, j, k: a
        # renamed external would read the wrong slot silently.
        assert [i.name for i in occ] == ["i", "j", "k"], occ
        assert sorted(i.name for i in vir) == ["a", "b", "c"], vir
        term_spins = ucc_term_index_spins(term) if ucc else {}
        assert all(term_spins.get(x) == spins.get(x) for x in "abcijk"), term_spins
        lines.append(f"    // Term {n}")
        for idx in occ:
            lines.append(f"    for (int {idx.name} = 0; {idx.name} < "
                         f"{_loop_bound(idx, term_spins.get(idx.name))}; ++{idx.name})")
        lines.append("    {")
        product = _term_coeff_product(term, term.factors, None, True)
        slot = f"out[(static_cast<std::size_t>(i) * {nj} + j) * {nk} + k]"
        if term.summed_indices:
            lines.append("        double acc = 0.0;")
            for idx in term.summed_indices:
                lines.append(
                    f"        for (int {idx.name} = 0; {idx.name} < "
                    f"{_loop_bound(idx, term_spins.get(idx.name))}; ++{idx.name})")
            lines.append(f"            acc += {product};")
            lines.append(f"        {slot} += acc;")
        else:
            lines.append(f"        {slot} += {product};")
        lines.append("    }")
    lines.append("}")
    return "\n".join(lines)
