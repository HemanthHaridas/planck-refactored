"""Split an emitted Planck translation unit into a header and N source shards.

The kernel registry used to `#include` every generated file into one TU; at
rank 4 with UCC that was ~76 MB of source in one `-O1` compile, which does not
fit in 8 GiB. Each generated file is now its own set of TUs in the
`planck_cc_generated` library, and a large one is split so that no single
compile holds more than its share.

The emitted text has a fixed shape, which this relies on and checks:

    <includes>
    namespace HartreeFock::Correlation::CC
    {
    <item>...           every item starts at column 0 and ends at a column-0
    } // namespace ...  `}` or `};`; everything between is indented

An item is a function definition or the one `struct <...>_residual_ops`.
Every function name is unique to its method and kind (`_lambda_`, `ucc_`), so
all of them get external linkage (`static` is dropped) and a declaration in the
header; the struct goes in the header whole. Any shard can then call anything.
"""
from __future__ import annotations

NAMESPACE_OPEN = "namespace HartreeFock::Correlation::CC"


def _split(text: str):
    lines = text.split("\n")
    try:
        ns = lines.index(NAMESPACE_OPEN)
    except ValueError:
        raise ValueError("emitted TU has no Planck CC namespace") from None
    if lines[ns + 1] != "{":
        raise ValueError("emitted TU: namespace not followed by '{'")
    includes = [ln for ln in lines[:ns] if ln.startswith("#include")]
    items, cur = [], None
    for ln in lines[ns + 2:]:
        if cur is None:
            if not ln.strip():
                continue
            if ln.startswith("} // namespace"):
                return includes, items
            if ln[0] in " \t{}":
                raise ValueError(f"emitted TU: unexpected line between items: {ln!r}")
            cur = [ln]
        else:
            cur.append(ln)
            if ln in ("}", "};"):
                items.append(cur)
                cur = None
    raise ValueError("emitted TU: namespace never closed")


def _declaration(item):
    """The signature lines up to the body's opening `{`, as a declaration."""
    body = item.index("{")
    return "\n".join(item[:body]) + ";"


def shard_translation_unit(text: str, n_shards: int, header_name: str):
    """(header text, [shard texts]) for *text* split into *n_shards* sources of
    about equal size, in emission order. Shards include *header_name*."""
    if n_shards < 1:
        raise ValueError("n_shards must be >= 1")
    includes, items = _split(text)
    structs, funcs = [], []
    for it in items:
        if it[0].startswith("struct "):
            structs.append(it)
        else:
            if it[0].startswith("static "):
                it = [it[0][len("static "):]] + it[1:]
            funcs.append(it)

    header = ["#pragma once", "// Auto-generated by ccgen (shard header)", ""]
    header += includes + ["", NAMESPACE_OPEN, "{", ""]
    for s in structs:
        header += s + [""]
    for f in funcs:
        header += [_declaration(f), ""]
    header += ["} // namespace HartreeFock::Correlation::CC", ""]

    sizes = [sum(len(ln) + 1 for ln in f) for f in funcs]
    target = sum(sizes) / n_shards
    groups, acc = [[]], 0
    for f, size in zip(funcs, sizes):
        # Cut where this function's midpoint passes the next boundary.
        if groups[-1] and acc + size / 2 > target * len(groups) and len(groups) < n_shards:
            groups.append([])
        groups[-1].append(f)
        acc += size
    groups += [[] for _ in range(n_shards - len(groups))]

    shards = []
    for g in groups:
        out = ["// Auto-generated by ccgen (shard)", f'#include "{header_name}"', "",
               NAMESPACE_OPEN, "{", ""]
        for f in g:
            out += f + [""]
        out += ["} // namespace HartreeFock::Correlation::CC", ""]
        shards.append("\n".join(out))
    return "\n".join(header), shards


if __name__ == "__main__":
    src = """#include "a.h"

namespace HartreeFock::Correlation::CC
{

Tensor2D build_W_x_ccsd(
    const int &a)
{
    return build_W_y_ccsd(a);
}

struct ccsd_residual_ops
{
    Tensor2D W;
};

static ccsd_residual_ops build_ccsd_residual_ops(
    const int &a)
{
    return ccsd_residual_ops{build_W_x_ccsd(a)};
}

} // namespace HartreeFock::Correlation::CC
"""
    h, s = shard_translation_unit(src, 2, "x.h")
    assert "struct ccsd_residual_ops\n{\n    Tensor2D W;\n};" in h
    assert "Tensor2D build_W_x_ccsd(\n    const int &a);" in h
    assert "ccsd_residual_ops build_ccsd_residual_ops(\n    const int &a);" in h
    assert "static" not in "".join(s)
    assert len(s) == 2 and "build_W_x_ccsd(\n" in s[0] and "build_ccsd_residual_ops(\n" in s[1]
    assert all('#include "x.h"' in x for x in s)
    h1, s1 = shard_translation_unit(src, 3, "x.h")
    assert len(s1) == 3 and "build_" not in s1[2].split("{", 1)[1]
    print("shard self-check ok")
